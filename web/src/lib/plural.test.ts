import { describe, expect, it } from 'vitest'
import { countLabel, plural } from './plural'

describe('русское множественное число', () => {
  const снимки = (n: number) => plural(n, 'снимок', 'снимка', 'снимков')

  it.each([
    [1, 'снимок'], [21, 'снимок'], [101, 'снимок'],
    [2, 'снимка'], [3, 'снимка'], [4, 'снимка'], [22, 'снимка'], [104, 'снимка'],
    [0, 'снимков'], [5, 'снимков'], [11, 'снимков'], [12, 'снимков'], [14, 'снимков'], [111, 'снимков'], [112, 'снимков'],
  ])('%i → %s', (n, expected) => {
    expect(снимки(n)).toBe(expected)
  })

  it('подписывает число', () => {
    expect(countLabel(24, 'снимок', 'снимка', 'снимков')).toBe('24 снимка')
  })
})
